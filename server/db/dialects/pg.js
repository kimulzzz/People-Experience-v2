// server/db/dialects/pg.js
// PostgreSQL dialect of the SQL storage (STORAGE_BACKEND=pg, `pg` driver) - same contract as mssql.js, so sqlStorage.js runs
// unchanged on both. Meant for a temporary UAT host (e.g. Render: DATABASE_URL); SQL Server stays the production target.
//
// What makes PostgreSQL behave like the SQL Server database (see schema.pg.sql):
//  * every text column is CITEXT: SQL Server's default collation is case-INSENSITIVE, so usernames, e-mail / PIC matching,
//    directorate / division names and aliases, setting keys, NIKs ... compare, group and are UNIQUE regardless of case;
//    exact comparisons use sql.bin() like SQL Server's BIN2 collation.
//  * type parsers return the same JS types as the mssql driver: BIGINT (COUNT(*)) and NUMERIC as numbers, DATE as a Date at
//    UTC midnight (never shifted by the server's time zone); BIT columns are BOOLEAN (true / false like mssql's bit).
//  * DATETIME2 columns are TIMESTAMPTZ(3); Date parameters are sent as UTC ISO strings and the session time zone is UTC.
//  * identity columns are GENERATED BY DEFAULT, so explicit ids can be inserted; syncIdentities() moves the sequences on
//    afterwards (SQL Server does that by itself).
// SQL text keeps named parameters (@name); query() turns them into $1..$n.
const fs = require('fs');
const path = require('path');
const pg = require('pg');

const name = 'pg';
const label = 'PostgreSQL';

// ------------------------------------------------------------------ connection
// DATABASE_URL when set (Render), otherwise PG_HOST / PG_PORT / PG_USER / PG_PASSWORD / PG_DATABASE. PG_SSL=1 turns TLS on
// (Render's EXTERNAL url needs it; its internal url does not). PG_POOL_MAX = pool size (default 10).
function connectionConfig() {
  const ssl = String(process.env.PG_SSL || '').trim() === '1' ? { rejectUnauthorized: false } : undefined;
  const base = process.env.DATABASE_URL
    ? { connectionString: process.env.DATABASE_URL }
    : {
      host: process.env.PG_HOST || 'localhost',
      port: parseInt(process.env.PG_PORT || '5432', 10),
      user: process.env.PG_USER,
      password: process.env.PG_PASSWORD,
      database: process.env.PG_DATABASE || 'peopleexperiencepx'
    };
  return {
    ...base,
    ...(ssl ? { ssl } : {}),
    max: parseInt(process.env.PG_POOL_MAX || '10', 10),
    idleTimeoutMillis: 30000,
    connectionTimeoutMillis: 15000,
    statement_timeout: 120000,
    options: '-c TimeZone=UTC',          // session time zone UTC (SQL Server: SYSUTCDATETIME / DATETIME2 hold UTC)
    types: { getTypeParser }
  };
}

// Same JS types as the mssql driver.
const PARSERS = {
  20: v => (v === null ? null : parseInt(v, 10)),               // BIGINT / COUNT(*) -> number
  1700: v => (v === null ? null : parseFloat(v)),               // NUMERIC / DECIMAL -> number
  1082: v => (v === null ? null : new Date(`${v}T00:00:00Z`))   // DATE -> Date at UTC midnight (mssql: useUTC)
};
function getTypeParser(oid, format) {
  return (format !== 'binary' && PARSERS[oid]) || pg.types.getTypeParser(oid, format);
}

let pool = null;
let ready = null;

function getPool() {
  if (!ready) {
    pool = new pg.Pool(connectionConfig());
    pool.on('error', err => console.error('[sqlStorage] pool error:', err.message));
    const p = pool;
    ready = p.query('SELECT 1').then(() => p).catch(async err => {
      ready = null; // allow a later retry instead of caching the failure
      pool = null;
      try { await p.end(); } catch (_) { /* ignore */ }
      throw err;
    });
  }
  return ready;
}

async function close() {
  if (ready) {
    const p = pool;
    ready = null;
    pool = null;
    if (p) await p.end();
  }
}

function identity() {
  if (process.env.DATABASE_URL) {
    try {
      const u = new URL(process.env.DATABASE_URL);
      return { server: u.hostname, database: decodeURIComponent(u.pathname.replace(/^\//, '')) };
    } catch (_) { return { server: 'DATABASE_URL', database: '' }; }
  }
  const cfg = connectionConfig();
  return { server: cfg.host, database: cfg.database };
}

// ------------------------------------------------------------------ typed parameters & query runner
const typed = (kind, v) => ({ __t: kind, v });

const paramValue = v => {
  if (v && typeof v === 'object' && '__t' in v) v = v.v;
  if (v === undefined) return null;
  if (v instanceof Date) return isNaN(v.getTime()) ? null : v.toISOString();
  return v;
};

// '@name' -> '$n' (the same name gets the same number); quoted strings, quoted identifiers and comments are left alone.
const converted = new Map();
function toPositional(text) {
  const hit = converted.get(text);
  if (hit) return hit;
  const names = [];
  let out = '';
  let i = 0;
  while (i < text.length) {
    const ch = text[i];
    if (ch === "'" || ch === '"') {
      let j = i + 1;
      while (j < text.length) {
        if (text[j] === ch) { if (text[j + 1] === ch) { j += 2; continue; } break; }
        j++;
      }
      out += text.slice(i, j + 1);
      i = j + 1;
      continue;
    }
    if (ch === '-' && text[i + 1] === '-') {
      const j = text.indexOf('\n', i);
      const end = j === -1 ? text.length : j;
      out += text.slice(i, end);
      i = end;
      continue;
    }
    if (ch === '@' && /[A-Za-z_]/.test(text[i + 1] || '')) {
      let j = i + 1;
      while (j < text.length && /[A-Za-z0-9_]/.test(text[j])) j++;
      const p = text.slice(i + 1, j);
      let n = names.indexOf(p);
      if (n === -1) { names.push(p); n = names.length - 1; }
      out += `$${n + 1}`;
      i = j;
      continue;
    }
    out += ch;
    i++;
  }
  const result = { text: out, names };
  if (converted.size > 5000) converted.clear();
  converted.set(text, result);
  return result;
}

// Runs a parameterized query on the pool, or inside a transaction when `tx` (a pool client) is given. -> { rows, rowCount }
async function query(text, params, tx) {
  const client = tx || await getPool();
  const c = toPositional(text);
  let res;
  if (c.names.length) {
    const values = c.names.map(n => {
      if (!params || !(n in params)) throw new Error(`[sqlStorage] missing parameter @${n}`);
      return paramValue(params[n]);
    });
    res = await client.query(c.text, values);
  } else {
    res = await client.query(c.text);
  }
  const last = Array.isArray(res) ? res[res.length - 1] : res;   // a multi-statement text returns one result per statement
  return { rows: last.rows || [], rowCount: last.rowCount || 0 };
}

// Rows changed by ONE INSERT / UPDATE / DELETE (same contract as mssql.rowCount)
async function rowCount(text, params, tx) {
  return (await query(text, params, tx)).rowCount;
}

async function inTransaction(work) {
  const p = await getPool();
  const client = await p.connect();
  try {
    await client.query('BEGIN');
    const out = await work(client);
    await client.query('COMMIT');
    return out;
  } catch (err) {
    try { await client.query('ROLLBACK'); } catch (_) { /* already rolled back */ }
    throw err;
  } finally {
    client.release();
  }
}

const isUniqueViolation = err => !!err && err.code === '23505';
const isDeadlock = err => !!err && (err.code === '40P01' || err.code === '40001');

// ------------------------------------------------------------------ SQL fragments (same names in mssql.js)
const sqlText = {
  now: 'now()',
  TRUE: 'TRUE',
  FALSE: 'FALSE',
  top: () => '',
  limit: n => `LIMIT ${n}`,
  dateStr: expr => `to_char(${expr}, 'YYYY-MM-DD')`,
  year: expr => `CAST(EXTRACT(YEAR FROM ${expr}) AS INT)`,
  month: expr => `CAST(EXTRACT(MONTH FROM ${expr}) AS INT)`,
  dateFromParts: (y, m, d) => `make_date(${y}, ${m}, ${d})`,
  len: expr => `length(${expr})`,
  bin: expr => `CAST(${expr} AS TEXT) COLLATE "C"`,
  nullText: 'CAST(NULL AS citext)',
  lockHint: '',
  forUpdate: 'FOR UPDATE',
  outInserted: () => '',
  outDeleted: () => '',
  returning: cols => `RETURNING ${cols}`,
  quoteId: id => `"${id}"`
};

// SQL Server's UPDLOCK/HOLDLOCK hint on a SELECT MAX(id) / COUNT(*) has no pg equivalent on aggregates: lock the table instead
// (released at the end of the transaction; blocks concurrent writers, not readers).
async function lockTable(tx, table) {
  await query(`LOCK TABLE dbo.${table} IN SHARE ROW EXCLUSIVE MODE`, {}, tx);
}

// INSERT ... ON CONFLICT (key) DO UPDATE - same spec as mssql.upsert (MERGE there; holdlock is a SQL Server hint, the conflict
// check on the unique key already serializes the row here). action -> rows[0].act 'INSERT' | 'UPDATE'.
function upsert({ table, key, cols, update, action = false }) {
  const ins = { ...key, ...cols };
  const set = Object.entries(update || cols).map(([c, v]) => `${c} = ${v}`).join(', ');
  return `INSERT INTO dbo.${table} (${Object.keys(ins).join(', ')}) VALUES (${Object.values(ins).join(', ')})
          ON CONFLICT (${Object.keys(key).join(', ')}) DO UPDATE SET ${set}${action ? "\n          RETURNING CASE WHEN xmax = 0 THEN 'INSERT' ELSE 'UPDATE' END AS act" : ''}`;
}

// Identity columns are GENERATED BY DEFAULT: an explicit id is just inserted (call syncIdentities afterwards).
async function insertWithIdentity(tx, table, text, params) {
  return query(text, params, tx);
}

// Moves the sequence of every identity column (or of the given tables) past the highest id, after explicit-id inserts.
// Never moves a sequence back (like SQL Server, an id handed out once is not reused after its row was deleted).
async function syncIdentities(tx, tables = null) {
  const cols = (await query(`SELECT table_name, column_name, pg_get_serial_sequence('dbo.' || table_name, column_name) AS seq
                             FROM information_schema.columns
                             WHERE table_schema = 'dbo' AND is_identity = 'YES' ORDER BY table_name`, {}, tx)).rows
    .filter(c => c.seq && (!tables || tables.includes(c.table_name)));
  for (const c of cols) {
    await query(`SELECT setval(@seq, GREATEST(COALESCE((SELECT MAX(${c.column_name}) FROM dbo.${c.table_name}), 0) + 1,
                                     (SELECT CASE WHEN is_called THEN last_value + 1 ELSE last_value END FROM ${c.seq})), false)`, { seq: c.seq }, tx);
  }
}

// ------------------------------------------------------------------ bulk insert (multi-row INSERT, in the given order)
async function bulkInsert(tx, table, columns, rows) {
  if (!rows.length) return;
  const per = Math.max(1, Math.floor(30000 / columns.length));   // pg allows 65535 parameters per statement
  for (let i = 0; i < rows.length; i += per) {
    const chunk = rows.slice(i, i + per);
    const values = [];
    const tuples = chunk.map(r => `(${r.map(v => { values.push(paramValue(v)); return `$${values.length}`; }).join(', ')})`);
    await (tx || await getPool()).query(`INSERT INTO dbo.${table} (${columns.map(c => c.name).join(', ')}) VALUES ${tuples.join(', ')}`, values);
  }
}

// ------------------------------------------------------------------ schema & catalog
async function applySchema() {
  const p = await getPool();
  // UNIQUE NULLS NOT DISTINCT (one Bankwide ESS row / one "all divisions" scope per key, like SQL Server) needs PostgreSQL 15+
  const v = parseInt((await p.query("SELECT current_setting('server_version_num') AS v")).rows[0].v, 10);
  if (v < 150000) throw new Error(`PostgreSQL 15 or newer is required (this server is ${Math.floor(v / 10000)}).`);
  const text = fs.readFileSync(path.join(__dirname, '..', 'schema.pg.sql'), 'utf8');
  await p.query(text);   // one simple-protocol call = one implicit transaction
}

async function tableExists(table) {
  return (await query('SELECT to_regclass(@t) IS NOT NULL AS ok', { t: `dbo.${table}` })).rows[0].ok === true;
}
async function columnExists(table, column) {
  return (await query(`SELECT 1 AS x FROM information_schema.columns WHERE table_schema = 'dbo' AND table_name = @t AND column_name = @c`,
    { t: table, c: column })).rows.length > 0;
}
async function dropTableIfExists(table, { onlyIfEmpty = false } = {}) {
  if (onlyIfEmpty && await tableExists(table) && (await query(`SELECT 1 AS x FROM dbo.${table} LIMIT 1`)).rows.length) return;
  await query(`DROP TABLE IF EXISTS dbo.${table}`);
}

async function serverInfo() {
  const r = (await query("SELECT current_database() AS db, current_setting('server_version') AS version")).rows[0];
  return { server: identity().server, database: r.db, edition: `PostgreSQL ${r.version}`, version: r.version };
}

// ------------------------------------------------------------------ configuration snapshot (raw rows of a table)
async function tableColumns(tx, table) {
  return (await query(`SELECT column_name AS name, data_type AS type_name, is_identity = 'YES' AS is_identity
                       FROM information_schema.columns WHERE table_schema = 'dbo' AND table_name = @t ORDER BY ordinal_position`, { t: table }, tx)).rows;
}

async function insertRawRows(tx, table, cols, rows, identity) {
  const text = `INSERT INTO dbo.${table} (${cols.map(c => `"${c.name}"`).join(', ')}) VALUES (${cols.map((c, i) => `$${i + 1}`).join(', ')})`;
  for (const row of rows) await tx.query(text, row.map(paramValue));
  if (identity) await syncIdentities(tx, [table]);
}

