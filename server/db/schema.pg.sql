-- ============================================================================
-- CIMB Niaga People Experience (PX) - PostgreSQL schema (STORAGE_BACKEND=pg, v2.61.0)
-- The same 41 tables, columns, CHECK constraints, uniques and indexes as schema.sql (SQL Server), including the columns
-- SQL Server databases get through boot ALTERs. Applied by server/db/dialects/pg.js (sqlStorage.init / migrate.js) as ONE
-- statement list in one implicit transaction; idempotent (IF NOT EXISTS everywhere), so it is safe on every boot.
--
-- Mapping from SQL Server (see the header of dialects/pg.js):
--  * every NVARCHAR / VARCHAR / CHAR column is CITEXT  -> case-insensitive like SQL Server's default collation
--    (comparison, GROUP BY, UNIQUE); lengths are not enforced by the type (the app trims the values it writes).
--  * BIT -> BOOLEAN, FLOAT -> DOUBLE PRECISION, TINYINT -> SMALLINT, DECIMAL -> NUMERIC, DATETIME2(3) -> TIMESTAMPTZ(3) (UTC).
--  * INT IDENTITY -> INT GENERATED BY DEFAULT AS IDENTITY (explicit ids allowed; sequences synced after imports).
--  * UNIQUE keys with a nullable column are NULLS NOT DISTINCT (SQL Server allows one NULL per key) - needs PostgreSQL 15+.
--  * Tables live in schema "dbo" so the shared SQL (dbo.px_*) is the same on both databases.
-- ============================================================================

